// Pulls real excerpts from this repo into Shot 05, so the "proof" screens can never drift
// into fabricated code. Run before rendering: `npm run proof`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

const sources = [
  { label: "STORY", path: ".claude/skills/instagram-reel-showrunner/SKILL.md", needle: "### Gate A", count: 4, highlight: 1 },
  { label: "STORY", path: "reels/reel-001/storyboard.csv", needle: "03,3.6,5.2", count: 3, highlight: 0 },
  { label: "MOTION", path: "studio/src/reel-001/motif.tsx", needle: "export const openingHead", count: 3, highlight: 0 },
  { label: "SOUND", path: "reels/reel-001/sfx_cues.csv", needle: "3.60,108", count: 4, highlight: 1 },
];

const excerpts = sources.map(({ label, path, needle, count, highlight }) => {
  const lines = readFileSync(join(root, path), "utf8").split("\n");
  const start = lines.findIndex((l) => l.includes(needle));
  if (start < 0) throw new Error(`"${needle}" not found in ${path}`);
  // Leading context line where one exists, so the gutter reads like a real crop.
  const from = Math.max(0, start - 1);
  return { label, path, startLine: from + 1, lines: lines.slice(from, start + count), highlight: highlight + (start - from) };
});

const out = join(root, "studio/src/reel-001/proof.generated.ts");
writeFileSync(
  out,
  `// Generated by scripts/extract-proof.mjs. Do not edit by hand.\n` +
    `export const proofExcerpts = ${JSON.stringify(excerpts, null, 2)} as const;\n`,
);
console.log(`wrote ${excerpts.length} excerpts -> ${out}`);
